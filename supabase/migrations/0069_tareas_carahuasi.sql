-- =============================================================================
-- 0069 · Estancia Carahuasi — Asignación y seguimiento de tareas
-- =============================================================================
-- Módulo exclusivo de Carahuasi. Incluye:
--   - aislamiento estricto por cliente y rol;
--   - baja lógica (nunca se destruye el historial);
--   - auditoría automática de cada alta/cambio/resultado/baja;
--   - RPCs seguras para administradores y operarios;
--   - publicación Realtime para actualizar el panel administrativo.
-- Es idempotente y no modifica eventos de los módulos existentes.
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.tareas (
  id text PRIMARY KEY,
  cliente_id text NOT NULL REFERENCES public.clientes(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  fecha date NOT NULL,
  asignado_email text NOT NULL,
  descripcion text NOT NULL CHECK (length(btrim(descripcion)) > 0),
  estado text NOT NULL DEFAULT 'pendiente'
    CHECK (estado IN ('pendiente', 'completada', 'no_completada')),
  observaciones_admin text,
  observaciones_operario text,
  asignada_por text NOT NULL,
  respondida_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  deleted_by text,
  CONSTRAINT tareas_asignado_email_fkey
    FOREIGN KEY (asignado_email) REFERENCES public.usuarios(email)
    ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS tareas_cliente_fecha_idx
  ON public.tareas (cliente_id, fecha DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS tareas_asignado_fecha_idx
  ON public.tareas (cliente_id, asignado_email, fecha DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS tareas_estado_fecha_idx
  ON public.tareas (cliente_id, estado, fecha DESC) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS public.tareas_historial (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarea_id text NOT NULL,
  cliente_id text NOT NULL REFERENCES public.clientes(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  accion text NOT NULL CHECK (accion IN ('creada', 'modificada', 'resultado_informado', 'eliminada')),
  actor_email text NOT NULL,
  antes jsonb,
  despues jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS tareas_historial_tarea_idx
  ON public.tareas_historial (tarea_id, created_at DESC);
CREATE INDEX IF NOT EXISTS tareas_historial_cliente_idx
  ON public.tareas_historial (cliente_id, created_at DESC);

ALTER TABLE public.tareas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tareas_historial ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.current_user_is_task_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT public.current_cliente_id() = 'estancia-carahuasi'
    AND (
      public.is_super_admin()
      OR EXISTS (
        SELECT 1
        FROM public.usuarios AS u
        WHERE lower(btrim(u.email)) = public.current_user_email()
          AND u.cliente_id = public.current_cliente_id()
          AND u.rol = 'administrador'
      )
    );
$$;

REVOKE ALL ON FUNCTION public.current_user_is_task_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.current_user_is_task_admin() TO authenticated;

DROP POLICY IF EXISTS tareas_select ON public.tareas;
CREATE POLICY tareas_select
  ON public.tareas FOR SELECT TO authenticated
  USING (
    cliente_id = public.current_cliente_id()
    AND cliente_id = 'estancia-carahuasi'
    AND deleted_at IS NULL
    AND (
      public.current_user_is_task_admin()
      OR lower(btrim(asignado_email)) = public.current_user_email()
    )
  );

-- Las escrituras pasan exclusivamente por RPCs auditadas. Sin policies de
-- INSERT/UPDATE/DELETE, un cliente no puede saltear las reglas llamando REST.
DROP POLICY IF EXISTS tareas_insert ON public.tareas;
DROP POLICY IF EXISTS tareas_update ON public.tareas;
DROP POLICY IF EXISTS tareas_delete ON public.tareas;

DROP POLICY IF EXISTS tareas_historial_select ON public.tareas_historial;
CREATE POLICY tareas_historial_select
  ON public.tareas_historial FOR SELECT TO authenticated
  USING (
    cliente_id = public.current_cliente_id()
    AND public.current_user_is_task_admin()
  );

CREATE OR REPLACE FUNCTION public.auditar_tarea()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_accion text;
  v_actor text := coalesce(public.current_user_email(), 'sistema');
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_accion := 'creada';
    INSERT INTO public.tareas_historial
      (tarea_id, cliente_id, accion, actor_email, antes, despues)
    VALUES
      (NEW.id, NEW.cliente_id, v_accion, v_actor, NULL, to_jsonb(NEW));
    RETURN NEW;
  END IF;

  IF OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL THEN
    v_accion := 'eliminada';
  ELSIF OLD.estado IS DISTINCT FROM NEW.estado
     OR OLD.observaciones_operario IS DISTINCT FROM NEW.observaciones_operario THEN
    v_accion := 'resultado_informado';
  ELSE
    v_accion := 'modificada';
  END IF;

  INSERT INTO public.tareas_historial
    (tarea_id, cliente_id, accion, actor_email, antes, despues)
  VALUES
    (NEW.id, NEW.cliente_id, v_accion, v_actor, to_jsonb(OLD), to_jsonb(NEW));
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS tareas_auditoria_trigger ON public.tareas;
CREATE TRIGGER tareas_auditoria_trigger
AFTER INSERT OR UPDATE ON public.tareas
FOR EACH ROW EXECUTE FUNCTION public.auditar_tarea();

CREATE OR REPLACE FUNCTION public.guardar_tarea_admin(
  p_id text,
  p_fecha date,
  p_asignado_email text,
  p_descripcion text,
  p_estado text,
  p_observaciones_admin text
)
RETURNS public.tareas
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_cliente text := public.current_cliente_id();
  v_email text := lower(btrim(p_asignado_email));
  v_actor text := public.current_user_email();
  v_row public.tareas;
BEGIN
  IF NOT public.current_user_is_task_admin() THEN
    RAISE EXCEPTION 'Solo un administrador de Carahuasi puede asignar tareas.' USING ERRCODE = '42501';
  END IF;
  IF NOT public.current_cliente_can_write() THEN
    RAISE EXCEPTION 'La cuenta no está habilitada para cargar datos.' USING ERRCODE = '42501';
  END IF;
  IF p_id IS NULL OR btrim(p_id) = '' OR p_fecha IS NULL OR coalesce(length(btrim(p_descripcion)), 0) = 0 THEN
    RAISE EXCEPTION 'Fecha, operario y descripción son obligatorios.';
  END IF;
  IF p_estado NOT IN ('pendiente', 'completada', 'no_completada') THEN
    RAISE EXCEPTION 'Estado de tarea inválido.';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.usuarios u
    WHERE lower(btrim(u.email)) = v_email
      AND u.cliente_id = v_cliente
      AND u.rol = 'operario'
  ) THEN
    RAISE EXCEPTION 'El usuario seleccionado no es un operario habilitado de Carahuasi.';
  END IF;

  SELECT * INTO v_row
  FROM public.tareas
  WHERE id = p_id AND cliente_id = v_cliente
  FOR UPDATE;

  IF FOUND THEN
    UPDATE public.tareas
    SET fecha = p_fecha,
        asignado_email = v_email,
        descripcion = btrim(p_descripcion),
        estado = p_estado,
        observaciones_admin = nullif(btrim(p_observaciones_admin), ''),
        observaciones_operario = CASE WHEN p_estado = 'pendiente' THEN NULL ELSE observaciones_operario END,
        respondida_at = CASE WHEN p_estado = 'pendiente' THEN NULL ELSE coalesce(respondida_at, now()) END,
        updated_at = now()
    WHERE id = p_id
    RETURNING * INTO v_row;
  ELSE
    INSERT INTO public.tareas (
      id, cliente_id, fecha, asignado_email, descripcion, estado,
      observaciones_admin, asignada_por, respondida_at
    ) VALUES (
      p_id, v_cliente, p_fecha, v_email, btrim(p_descripcion), p_estado,
      nullif(btrim(p_observaciones_admin), ''), v_actor,
      CASE WHEN p_estado = 'pendiente' THEN NULL ELSE now() END
    ) RETURNING * INTO v_row;
  END IF;

  RETURN v_row;
END;
$$;

CREATE OR REPLACE FUNCTION public.informar_tarea(
  p_tarea_id text,
  p_estado text,
  p_observaciones text
)
RETURNS public.tareas
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_row public.tareas;
BEGIN
  IF NOT public.current_cliente_can_write() THEN
    RAISE EXCEPTION 'La cuenta no está habilitada para cargar datos.' USING ERRCODE = '42501';
  END IF;
  IF p_estado NOT IN ('completada', 'no_completada') THEN
    RAISE EXCEPTION 'El resultado debe ser Completada o No completada.';
  END IF;
  IF p_estado = 'no_completada' AND nullif(btrim(p_observaciones), '') IS NULL THEN
    RAISE EXCEPTION 'La observación es obligatoria cuando la tarea no se completó.';
  END IF;

  UPDATE public.tareas
  SET estado = p_estado,
      observaciones_operario = nullif(btrim(p_observaciones), ''),
      respondida_at = now(),
      updated_at = now()
  WHERE id = p_tarea_id
    AND cliente_id = public.current_cliente_id()
    AND cliente_id = 'estancia-carahuasi'
    AND deleted_at IS NULL
    AND lower(btrim(asignado_email)) = public.current_user_email()
  RETURNING * INTO v_row;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No podés modificar esta tarea o la tarea ya no está disponible.' USING ERRCODE = '42501';
  END IF;
  RETURN v_row;
END;
$$;

CREATE OR REPLACE FUNCTION public.eliminar_tarea_admin(p_tarea_id text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF NOT public.current_user_is_task_admin() THEN
    RAISE EXCEPTION 'Solo un administrador puede eliminar tareas.' USING ERRCODE = '42501';
  END IF;
  IF NOT public.current_cliente_can_write() THEN
    RAISE EXCEPTION 'La cuenta no está habilitada para cargar datos.' USING ERRCODE = '42501';
  END IF;

  UPDATE public.tareas
  SET deleted_at = now(),
      deleted_by = public.current_user_email(),
      updated_at = now()
  WHERE id = p_tarea_id
    AND cliente_id = public.current_cliente_id()
    AND deleted_at IS NULL;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'La tarea no existe o ya fue eliminada.';
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.guardar_tarea_admin(text,date,text,text,text,text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.informar_tarea(text,text,text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.eliminar_tarea_admin(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.guardar_tarea_admin(text,date,text,text,text,text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.informar_tarea(text,text,text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.eliminar_tarea_admin(text) TO authenticated;

GRANT SELECT ON public.tareas TO authenticated;
GRANT SELECT ON public.tareas_historial TO authenticated;

UPDATE public.clientes
SET modulos_habilitados = CASE
  WHEN 'tareas' = ANY(modulos_habilitados) THEN modulos_habilitados
  ELSE array_append(modulos_habilitados, 'tareas')
END,
updated_at = now()
WHERE id = 'estancia-carahuasi';

-- La publicación puede existir o no según la configuración del proyecto.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime')
     AND NOT EXISTS (
       SELECT 1 FROM pg_publication_tables
       WHERE pubname = 'supabase_realtime'
         AND schemaname = 'public'
         AND tablename = 'tareas'
     ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.tareas;
  END IF;
EXCEPTION
  WHEN insufficient_privilege THEN
    RAISE NOTICE 'No se pudo agregar tareas a Realtime automáticamente; habilitarla desde Database > Replication.';
  WHEN duplicate_object THEN
    NULL;
END $$;

COMMIT;

SELECT id, nombre, modulos_habilitados
FROM public.clientes
WHERE id = 'estancia-carahuasi';

